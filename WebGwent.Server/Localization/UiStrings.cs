    public static string Get(string key, AppLanguage language)
    {
        var dict = language == AppLanguage.Ru ? Ru : En;
        if (dict.TryGetValue(key, out var value))
            return value;
        if (En.TryGetValue(key, out var fallback))
            return fallback;
        return key;
    }
